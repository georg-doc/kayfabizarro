import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const require = createRequire(import.meta.url);
const here = path.dirname(new URL(import.meta.url).pathname);
const C = require(path.join(here, '..', 'brush-core.js'));
const fflate = require(path.join(here, '..', 'vendor', 'fflate-0.8.3.umd.js'));

let pass = 0, fail = 0;
const results = [];
function t(name, fn) {
  try { fn(); pass++; results.push(['PASS', name]); }
  catch (e) { fail++; results.push(['FAIL', name + ' — ' + e.message]); }
}
const ok = (c, m) => { if (!c) throw Error(m || 'assertion failed'); };
const throwsLike = (fn, re) => { try { fn(); } catch (e) { if (re.test(e.message)) return; throw Error('wrong error: ' + e.message); } throw Error('did not throw'); };

/* synthetic NSKeyedArchiver plist, generated by Python's plistlib at test time (no binary fixtures in git) */
function synthArchive(fields) {
  const py = `
import plistlib,sys,json
f=json.loads(sys.argv[1])
root={'$class':plistlib.UID(2),'name':plistlib.UID(3)}
root.update(f)
d={'$version':100000,'$archiver':'NSKeyedArchiver','$top':{'root':plistlib.UID(1)},
   '$objects':['$null',root,{'$classname':'SilicaBrush','$classes':['SilicaBrush','NSObject']},'Synthetic Test Brush']}
sys.stdout.buffer.write(plistlib.dumps(d,fmt=plistlib.FMT_BINARY))`;
  return new Uint8Array(execFileSync('python3', ['-c', py, JSON.stringify(fields)]));
}
function fakePng() { return new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0]); }

const ARCH = synthArchive({ dynamicsPressureSize: 0.5, dynamicsSpeedOpacity: 0.7, plotSpacing: 0.1, shapeScatter: 1.0, shapeRotation: 0.0, taperEndLength: 0.05, taperSize: 0.6, dynamicsGlazeType: 1, dynamicsGlazeFlow: 0.5 });

t('bplist: NSKeyedArchiver root decodes to flat SilicaBrush fields', () => {
  const s = C.unarchive(C.parseBplist(ARCH));
  ok(s.$class === 'SilicaBrush', 'class ' + s.$class);
  ok(s.name === 'Synthetic Test Brush', 'name');
  ok(Math.abs(s.dynamicsPressureSize - 0.5) < 1e-9, 'float');
  ok(s.dynamicsGlazeType === 1, 'int');
});
t('bplist: rejects non-plist bytes', () => throwsLike(() => C.parseBplist(new Uint8Array(64).fill(7)), /not a binary plist/));
t('bplist: rejects truncated file', () => throwsLike(() => C.parseBplist(ARCH.slice(0, ARCH.length - 10)), /./));
t('bplist: rejects corrupted offset table', () => {
  const b = ARCH.slice(); const T = b.length - 32; b[T + 31] = 0xff; b[T + 30] = 0xff; // offset table beyond file
  throwsLike(() => C.parseBplist(b), /Malformed|out of/);
});

t('zip: valid single brush imports (archive + shape)', () => {
  const z = fflate.zipSync({ 'Brush.archive': ARCH, 'Shape.png': fakePng(), 'QuickLook/Thumbnail.png': fakePng() });
  const r = C.inspectBrushZip(z, fflate);
  ok(r.settings.name === 'Synthetic Test Brush'); ok(r.thumbPng && !r.grainPng);
});
t('zip: Reset/ copies are ignored, active root entries win', () => {
  const z = fflate.zipSync({ 'Reset/Brush.archive': new Uint8Array(10), 'Brush.archive': ARCH, 'Shape.png': fakePng() });
  ok(C.inspectBrushZip(z, fflate).settings.name === 'Synthetic Test Brush');
});
t('zip: path traversal rejected', () => throwsLike(() => C.inspectBrushZip(fflate.zipSync({ '../evil.png': fakePng(), 'Brush.archive': ARCH }), fflate), /Unsafe path/));
t('zip: missing Shape.png rejected', () => throwsLike(() => C.inspectBrushZip(fflate.zipSync({ 'Brush.archive': ARCH }), fflate), /Shape.png missing/));
t('zip: single-brush API refuses a .brushset with a clear message', () => throwsLike(() => C.inspectBrushZip(fflate.zipSync({ 'brushset.plist': new Uint8Array(4), 'x/Brush.archive': ARCH }), fflate), /brushset/));

/* ---------------- .brushset ---------------- */
const enc = s => new TextEncoder().encode(s);
const xmlSet = (name, ids) => enc('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n\t<key>brushes</key>\n\t<array>' + ids.map(i => '<string>' + i + '</string>').join('') + '</array>\n\t<key>name</key>\n\t<string>' + name + '</string>\n</dict>\n</plist>\n');
t('xml plist: attributes, doctype, entities, empty array', () => {
  const r = C.parseXmlPlist('<?xml version="1.0"?><!DOCTYPE x><plist version="1.0"><dict><key>name</key><string>Ink &amp; Co</string><key>n</key><integer>3</integer><key>t</key><true/><key>e</key><array/></dict></plist>');
  ok(r.name === 'Ink & Co' && r.n === 3 && r.t === true && Array.isArray(r.e) && !r.e.length, JSON.stringify(r));
});
t('brushset: folders imported in plist order, Reset/ skipped, name read', () => {
  const z = fflate.zipSync({
    'brushset.plist': xmlSet('Test Set', ['BBB', 'AAA']),
    'AAA/Brush.archive': ARCH, 'AAA/Shape.png': fakePng(), 'AAA/Reset/Brush.archive': new Uint8Array(9), 'AAA/Reset/Shape.png': fakePng(),
    'BBB/Brush.archive': ARCH, 'BBB/Shape.png': fakePng(), 'BBB/Grain.png': fakePng(), 'BBB/QuickLook/Thumbnail.png': fakePng(),
    'BBB/AuthorPicture/AuthorPicture.png': fakePng()
  });
  const r = C.inspectArchive(z, fflate);
  ok(r.kind === 'brushset' && r.setName === 'Test Set', r.kind + ' ' + r.setName);
  ok(r.brushes.map(b => b.folder).join() === 'BBB,AAA', r.brushes.map(b => b.folder).join());
  ok(r.brushes[0].grainPng && r.brushes[0].thumbPng && !r.brushes[1].grainPng, 'parts');
  ok(!r.skipped.length, JSON.stringify(r.skipped));
});
t('brushset: a broken brush is skipped with reason, the rest imports', () => {
  const z = fflate.zipSync({ 'brushset.plist': xmlSet('S', ['A', 'B']), 'A/Brush.archive': ARCH, 'A/Shape.png': fakePng(), 'B/Brush.archive': new Uint8Array(50) });
  const r = C.inspectArchive(z, fflate);
  ok(r.brushes.length === 1 && r.skipped.length === 1 && /plist/.test(r.skipped[0].reason), JSON.stringify(r.skipped));
});
t('brushset: path traversal inside a set rejected', () => throwsLike(() => C.inspectArchive(fflate.zipSync({ 'brushset.plist': xmlSet('S', []), 'A/../../x/Brush.archive': ARCH }), fflate), /Unsafe path/));
t('brushset: missing or unreadable brushset.plist still imports folders', () => {
  const r = C.inspectArchive(fflate.zipSync({ 'brushset.plist': enc('garbage'), 'A/Brush.archive': ARCH, 'A/Shape.png': fakePng() }), fflate);
  ok(r.kind === 'brushset' && r.brushes.length === 1 && r.setName === null);
});

/* ---------------- pressure curves ---------------- */
t('curve: unordered "{x, y}" points parse and sort; identity curve → null', () => {
  const c = C.parseCurve({ points: ['{0.000000, 0.000000}', '{1.000000, 1.000000}', '{0.879447, 0.725000}', '{0.532570, 0.273542}'] });
  ok(c.length === 4 && c[1][0] < c[2][0], JSON.stringify(c));
  ok(C.parseCurve({ points: ['{0, 0}', '{1, 1}'] }) === null, 'identity');
});
t('curve: monotone cubic hits the points, stays in [0,1] and monotone', () => {
  const pts = [[0, 0], [0.53257, 0.273542], [0.879447, 0.725], [1, 1]], f = C.curveFn(pts);
  for (const [x, y] of pts) ok(Math.abs(f(x) - y) < 1e-9, 'point ' + x);
  let prev = -1; for (let x = 0; x <= 1.0001; x += 0.01) { const y = f(x); ok(y >= prev - 1e-9 && y >= 0 && y <= 1, 'x ' + x); prev = y; }
});
t('zip: highly compressed oversize member (zip bomb) rejected before inflate', () => {
  const z = fflate.zipSync({ 'Brush.archive': ARCH, 'Shape.png': new Uint8Array(25e6) }, { level: 9 });
  ok(z.length < 1e6, 'fixture should be small'); throwsLike(() => C.inspectBrushZip(z, fflate), /too large/);
});
t('zip: non-zip rejected', () => throwsLike(() => C.inspectBrushZip(new Uint8Array(100), fflate), /Not a ZIP/));

/* ---------------- stamper ---------------- */
const P0 = C.mapSettings(C.unarchive(C.parseBplist(ARCH)));
const line = (n, dx, dt, p) => Array.from({ length: n }, (_, i) => ({ x: 50 + i * dx, y: 100, t: i * dt, p: typeof p === 'function' ? p(i / (n - 1)) : p, alt: null }));
const stroke = (params, points, seed = 3, size = 40) => C.stampsForStroke({ size, seed, params, points });
const mean = a => a.reduce((s, v) => s + v, 0) / a.length;

t('stamper: same seed → identical stamps (replay determinism)', () => {
  const a = stroke(P0, line(40, 4, 10, .7)), b = stroke(P0, line(40, 4, 10, .7));
  ok(JSON.stringify(a) === JSON.stringify(b));
});
t('stamper: different seed → different scatter', () => {
  ok(JSON.stringify(stroke(P0, line(40, 4, 10, .7), 1)) !== JSON.stringify(stroke(P0, line(40, 4, 10, .7), 2)));
});
t('stamper: live incremental feed equals replay (without end taper)', () => {
  const pts = line(30, 5, 12, .8), P = Object.assign({}, P0, { taperEnd: 0 });
  const st = C.createStamper({ size: 40, seed: 9, params: P }); const live = []; for (const p of pts) st.add(p, live);
  ok(JSON.stringify(live) === JSON.stringify(stroke(P, pts, 9)));
});
t('pressure: higher pressure → larger stamps (pressureSize > 0)', () => {
  const P = Object.assign({}, P0, { pressureSize: 1, jitterSize: 0, taperEnd: 0, speedSize: 0 });
  ok(mean(stroke(P, line(40, 4, 10, .9)).map(s => s.size)) > 2.5 * mean(stroke(P, line(40, 4, 10, .3)).map(s => s.size)));
});
t('pressure: pressureOpacity lowers alpha at light pressure', () => {
  const P = Object.assign({}, P0, { pressureOpacity: .8, speedOpacity: 0, jitterOpacity: 0 });
  ok(mean(stroke(P, line(40, 4, 10, .2)).map(s => s.alpha)) < mean(stroke(P, line(40, 4, 10, 1)).map(s => s.alpha)));
});
t('speed: speedOpacity > 0 → fast strokes lighter', () => {
  const P = Object.assign({}, P0, { speedOpacity: .76, speedSize: 0 });
  const slow = mean(stroke(P, line(80, 2, 20, .7)).map(s => s.alpha)), fast = mean(stroke(P, line(80, 8, 2, .7)).map(s => s.alpha));
  ok(fast < slow * 0.6, `slow ${slow.toFixed(3)} fast ${fast.toFixed(3)}`);
});
t('speed: negative speedSize (CRAYONIC -0.267) → fast strokes wider', () => {
  const P = Object.assign({}, P0, { speedSize: -0.267, jitterSize: 0, taperEnd: 0 });
  ok(mean(stroke(P, line(80, 8, 2, .7)).map(s => s.size)) > mean(stroke(P, line(80, 2, 20, .7)).map(s => s.size)) * 1.15);
});
t('rotation: rotation 1 / scatter 0 → stamp angle follows heading', () => {
  const P = Object.assign({}, P0, { rotation: 1, scatter: 0 });
  const diag = Array.from({ length: 30 }, (_, i) => ({ x: 10 + i * 4, y: 10 + i * 4, t: i * 10, p: .7, alt: null }));
  const s = stroke(P, diag).slice(1);
  ok(s.every(x => Math.abs(x.angle - Math.PI / 4) < 1e-6));
});
t('scatter: scatter 1 spreads angles over the full circle', () => {
  const P = Object.assign({}, P0, { rotation: 0, scatter: 1 });
  const a = stroke(P, line(200, 3, 10, .7)).map(s => s.angle);
  ok(Math.max(...a) - Math.min(...a) > 5.5);
});
t('taper: end taper shrinks the last stamps', () => {
  const P = Object.assign({}, P0, { taperEnd: .05, taperSize: .6, jitterSize: 0, speedSize: 0 });
  const s = stroke(P, line(80, 4, 10, .8)); const mid = s[Math.floor(s.length / 2)].size;
  ok(s[s.length - 1].size < mid * 0.6, `${s[s.length - 1].size} vs ${mid}`);
});
t('spacing: half spacing → about twice the stamps', () => {
  const a = stroke(Object.assign({}, P0, { spacing: .2, jitterSize: 0 }), line(60, 5, 10, .8)).length;
  const b = stroke(Object.assign({}, P0, { spacing: .1, jitterSize: 0 }), line(60, 5, 10, .8)).length;
  ok(b / a > 1.7 && b / a < 2.3, `${a} → ${b}`);
});

t('curve: a soft size curve makes light pressure thinner than linear', () => {
  const P = Object.assign({}, P0, { pressureSize: 1, jitterSize: 0, taperEnd: 0, speedSize: 0 });
  const lin = stroke(P, line(40, 4, 10, .5)), cur = stroke(Object.assign({}, P, { sizeCurve: [[0, 0], [0.53, 0.27], [0.88, 0.72], [1, 1]] }), line(40, 4, 10, .5));
  ok(mean(cur.map(s => s.size)) < mean(lin.map(s => s.size)) * 0.7);
});

/* ---------------- optional: real private brushes from BRUSH_DIR ---------------- */
const dir = (process.env.BRUSH_DIR && process.env.BRUSH_DIR.replace(/^~/, os.homedir())) ||
  [path.join(here, '..', 'brushes'), path.join(here, '..', '..', 'KFB-ToolBox/_inbox/KFB_HUB/30_DECISIONS/replies/KFB_BRUSH_PLAYGROUND_R1/Demo Brushes')].find(d => fs.existsSync(d));
if (dir && fs.existsSync(dir)) {
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.brush'));
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.brushset'))) {
    t('private brushset imports: ' + f, () => {
      const r = C.inspectArchive(fs.readFileSync(path.join(dir, f)), fflate);
      ok(r.kind === 'brushset' && r.brushes.length > 0 && !r.skipped.length, r.brushes.length + ' brushes, skipped ' + JSON.stringify(r.skipped));
      ok(r.setName && r.order === r.brushes.length, 'name/order ' + r.setName + ' ' + r.order);
      ok(r.brushes.every(b => !b.folder.includes('Reset')), 'Reset copy imported');
      return r;
    });
  }
  for (const f of files) {
    t('private brush decodes: ' + f, () => {
      const r = C.inspectBrushZip(fs.readFileSync(path.join(dir, f)), fflate);
      ok(r.settings.$class === 'SilicaBrush' && r.shapePng.length > 100, 'shape/class');
      const n = Object.keys(r.settings).length; ok(n >= 40, n + ' fields');
    });
  }
  const cr = files.find(f => /CRAYONIC/.test(f));
  if (cr) t('CRAYONIC decoded values match R1.3 archive audit', () => {
    const s = C.inspectBrushZip(fs.readFileSync(path.join(dir, cr)), fflate).settings;
    const close = (a, b) => Math.abs(a - b) < 0.001;
    ok(close(s.dynamicsPressureSize, 1) && close(s.dynamicsPressureOpacity, .408) && close(s.dynamicsSpeedSize, -.267) && close(s.dynamicsSpeedOpacity, .763) && close(s.dynamicsTiltSize, .391) && close(s.shapeScatter, 1));
  });
} else results.push(['SKIP', 'private brush checks (no ./brushes folder; set BRUSH_DIR)']);

for (const [s, n] of results) console.log(s.padEnd(5), n);
console.log(`\n${pass} passed, ${fail} failed`);
