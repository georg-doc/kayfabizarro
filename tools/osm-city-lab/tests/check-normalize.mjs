import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { normalizeOverpass } from '../src/osm/normalize.js';
import { buildConsumerScene } from '../src/export/scene-recipe.js';
const raw=JSON.parse(await fs.readFile(new URL('fixture.overpass.json',import.meta.url),'utf8'));
const spec=JSON.parse(await fs.readFile(new URL('../data/ehrenfeld-v0/SOURCE_SPEC.json',import.meta.url),'utf8'));
const a=normalizeOverpass(raw,spec,{fixture:true});
const b=normalizeOverpass(raw,spec,{fixture:true});
assert.deepEqual(a,b);
assert.equal(a.features.roads.length,1);
assert.equal(a.features.buildings.length,1);
assert.equal(a.features.landuse.length,1);
assert.equal(a.features.buildings[0].heightM,9.3);
assert.equal(a.features.buildings[0].id,'way/200');
assert.equal(a.features.roads[0].id,'way/100');
assert.ok(Number.isFinite(a.features.roads[0].widthM));
const scene=buildConsumerScene(a);
assert.equal(scene.schema,'kfb.osm-city.consumer-scene.v0');
assert.equal(scene.ownerContract.worldHost,'georg-doc/KFB-Travel-Globe');
assert.equal(scene.anchors.length,4);
console.log('PASS check-normalize: deterministic fixture, IDs, fallback height, S2 export');
